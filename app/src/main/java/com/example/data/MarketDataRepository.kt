    private fun generateSampleCandles(start: Float, end: Float, count: Int): List<CandleStick> {
        val candles = mutableListOf<CandleStick>()
        var current = start
        val step = (end - start) / count
        val times = listOf(
            "09:30", "10:00", "10:30", "11:00", "11:30", "12:00",
            "12:30", "13:00", "13:30", "14:00", "14:30", "15:00", "15:30", "16:00"
        )
        for (i in 0 until count) {
            val variance = (step.coerceAtLeast(0.5f) * (if (i % 2 == 0) 0.6f else -0.4f))
            val openVal = current
            val closeVal = (current + step + variance).coerceAtLeast(1f)
            val highVal = maxOf(openVal, closeVal) + (Math.abs(step) * 0.8f).coerceAtLeast(0.3f)
            val lowVal = minOf(openVal, closeVal) - (Math.abs(step) * 0.7f).coerceAtLeast(0.3f)
            candles.add(
                CandleStick(
                    timestamp = times.getOrElse(i) { "$i:00" },
                    open = openVal,
                    high = highVal,
                    low = lowVal,
                    close = closeVal
                )
            )
            current = closeVal
        }
        return candles
    }
